"""
JobExecutionLog model — Phase 7.

Lightweight record of every scheduled job execution.
Allows Super Admin to monitor whether automation is working correctly.

Entries are INSERT-only. Completed runs update the single row via
execution_id lookup (the scheduler service patches started → finished).

Security:
  - No secrets are stored here.
  - Only Super Admin can read these records via the admin API.
"""
from __future__ import annotations

import enum as pyenum
import uuid
from datetime import datetime
from typing import Any, Optional

from sqlalchemy import (
    DateTime,
    Enum,
    Integer,
    JSON,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base
from app.models._types import utcnow

_jsonb = JSONB().with_variant(JSON(), "sqlite")


class JobStatus(str, pyenum.Enum):
    running   = "running"
    success   = "success"
    failed    = "failed"
    skipped   = "skipped"   # idempotency guard triggered — job was a no-op


class JobExecutionLog(Base):
    """
    One row per job execution.

    Lifecycle:
      1. INSERT with status=running at job start.
      2. UPDATE status=success/failed/skipped at job end.

    The execution_id is generated by the job runner and used to locate the
    row for the completion update.
    """
    __tablename__ = "job_execution_logs"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)

    # Stable job identifier (e.g. "tournament_auto_transition")
    job_name: Mapped[str] = mapped_column(
        String(100), nullable=False, index=True
    )

    # Unique per run — used to patch the row on completion
    execution_id: Mapped[str] = mapped_column(
        String(80), nullable=False, unique=True, index=True
    )

    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        server_default=text("now()"),
        index=True,
    )
    completed_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # Wall-clock milliseconds (set on completion)
    duration_ms: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    status: Mapped[JobStatus] = mapped_column(
        Enum(JobStatus, name="job_status_enum", native_enum=False),
        nullable=False,
        default=JobStatus.running,
        index=True,
    )

    # How many DB rows/entities were processed (informational)
    records_affected: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)

    # First 2 000 chars of the exception message if status=failed
    error_summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Any extra structured data (no secrets)
    meta: Mapped[Optional[dict[str, Any]]] = mapped_column(_jsonb, nullable=True)

    def __repr__(self) -> str:
        return (
            f"<JobExecutionLog job={self.job_name!r} "
            f"exec={self.execution_id!r} status={self.status}>"
        )
